import React from 'react';
import {act,create} from 'react-test-renderer';
import {Text,TextInput} from 'react-native';
import {ListAction} from '../ui/ListPageUI';
const mockPush=jest.fn(),mockReplace=jest.fn(),mockExecute=jest.fn(),mockFirst=jest.fn(),mockPage=jest.fn();
jest.mock('expo-router',()=>({useLocalSearchParams:()=>({projectId:'p',timelineId:'old-timeline'}),useRouter:()=>({push:mockPush,replace:mockReplace,back:jest.fn()})}));
jest.mock('../storage/databaseClient',()=>({getDatabase:()=>({getFirstAsync:mockFirst})}));
jest.mock('./useLiveRefresh',()=>({useLiveRefresh:jest.fn()}));
jest.mock('./useUnsavedChanges',()=>({useUnsavedChanges:()=>((fn:()=>void)=>fn())}));
jest.mock('../tasks/executorEvents',()=>({executorWakePort:{signal:jest.fn()}}));
jest.mock('./CreativeAssetPicker',()=>({CreativeAssetPicker:()=>null}));
jest.mock('./runtime',()=>({creativeService:()=>({execute:mockExecute,versionsByIds:async()=>[]})}));
jest.mock('./timelines',()=>({readTimelinePage:mockPage,timelineSpec:{parse:(value:unknown)=>value}}));
jest.mock('./fileImport',()=>({saveCreativeText:jest.fn()}));
jest.mock('./timelinePackage',()=>({createTimelinePackage:jest.fn()}));
import {TimelineScreen} from './TimelineScreen';
test('audit reproduction: saving an edited exact timeline leaves only original snapshot renderable',async()=>{
 const spec={schemaVersion:1,orientation:'portrait',clips:[{versionId:'video-v1',startMs:0,durationMs:5000,caption:''}],audio:null};
 mockFirst.mockResolvedValue({id:'old-timeline',project_id:'p',title:'Original snapshot',created_at:1,spec_json:JSON.stringify(spec)});
 mockExecute.mockResolvedValue({status:'completed',value:{timelineId:'new-timeline'}});
 let tree!:ReturnType<typeof create>;
 await act(async()=>{tree=create(<TimelineScreen/>);});
 const click=async(label:string)=>act(async()=>tree.root.findAllByType(ListAction).find(node=>node.props.label===label)!.props.onPress());
 await click('载入副本继续编辑');
 act(()=>tree.root.findAllByType(TextInput).find(node=>node.props.accessibilityLabel==='工程名称')!.props.onChangeText('Edited snapshot'));
 await click('保存新工程快照');
 expect(mockExecute).toHaveBeenCalledWith(expect.objectContaining({name:'timeline.create',payload:expect.objectContaining({title:'Edited snapshot'})}),expect.any(String));
 expect(tree.root.findAllByType(Text).some(node=>String(node.props.children).includes('Edited snapshot'))).toBe(false);
 expect(mockReplace).not.toHaveBeenCalled();expect(mockPush).not.toHaveBeenCalled();expect(mockPage).not.toHaveBeenCalled();
 await click('在本机合成');
 expect(mockExecute).toHaveBeenLastCalledWith({name:'timeline.render',payload:{id:'old-timeline'}},expect.any(String));
 act(()=>tree.unmount());
});
